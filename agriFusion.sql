CREATE DATABASE agriFusion_UK;
USE agriFusion_UK;
CREATE TABLE Farm (
farm_id INT PRIMARY KEY,
farm_code VARCHAR(10) NOT NULL,
farm_name VARCHAR(50) NOT NULL,
owner_ssn VARCHAR(15) NOT NULL,
phone VARCHAR(15),
email VARCHAR(50),
address_line1 VARCHAR(50),
address_line2 VARCHAR(50),
address_line3 VARCHAR(50),
city VARCHAR(30),
district VARCHAR(30),
province VARCHAR(30),
country VARCHAR(30),
latitude DECIMAL(8,6),
longitude DECIMAL(9,6),
total_land_area DECIMAL(8,2),
soil_type VARCHAR(30),
irrigation_type VARCHAR(30),
status VARCHAR(10),
created_date DATETIME,
modified_date DATETIME
);
CREATE TABLE Field (
field_id INT PRIMARY KEY,
farm_id INT NOT NULL,
field_code VARCHAR(10) NOT NULL,
name VARCHAR(30),
area DECIMAL(8,2),
boundary TEXT,
elevation DECIMAL(6,2),
slope_percent DECIMAL(4,2),
soil_type VARCHAR(30),
soil_pH DECIMAL(3,1),
drainage_class VARCHAR(30),
irrigation_method VARCHAR(30),
water_source VARCHAR(30),
last_soil_test_date DATE,
status VARCHAR(10),
created_date DATETIME,
last_updated_date DATETIME,
FOREIGN KEY (farm_id) REFERENCES Farm(farm_id)
);
CREATE TABLE Crop (
crop_id INT PRIMARY KEY,
crop_code VARCHAR(10) NOT NULL,
crop_name VARCHAR(50) NOT NULL,
variety VARCHAR(30),
growth_duration DECIMAL(4,2),
opt_min_temp DECIMAL(4,1),
opt_max_temp DECIMAL(4,1),
opt_rainfall DECIMAL(6,1),
pref_min_soil_pH DECIMAL(3,1),
pref_max_soil_pH DECIMAL(3,1),
planting_depth_cm DECIMAL(4,1),
row_spacing_cm DECIMAL(4,1),
plant_spacing_cm DECIMAL(4,1),
expected_yield_per_ha DECIMAL(8,2),
market_grade_rule TEXT
);
CREATE TABLE Planting (
planting_id INT PRIMARY KEY,
field_id INT NOT NULL,
crop_id INT NOT NULL,
season_name VARCHAR(20),
planting_date DATE,
expected_harvest_start_date DATE,
expected_harvest_end_date DATE,
area_planted DECIMAL(8,2),
seed_lot_number VARCHAR(20),
seed_source VARCHAR(50),
planting_method VARCHAR(30),
planting_density DECIMAL(4,3),
note TEXT,
status VARCHAR(10),
FOREIGN KEY (field_id) REFERENCES Field(field_id),
FOREIGN KEY (crop_id) REFERENCES Crop(crop_id)
);
CREATE TABLE Harvest (
harvest_id INT PRIMARY KEY,
planting_id INT NOT NULL,
harvest_date DATE,
harvest_start_time TIME,
harvest_end_time TIME,
harvest_area DECIMAL(8,2),
quantity DECIMAL(8,2),
quantity_unit VARCHAR(10),
moisture_percent DECIMAL(4,1),
wastage DECIMAL(7,2),
labour_hour DECIMAL(5,1),
storage_location VARCHAR(30),
batch_code VARCHAR(15),
note TEXT,
created_date DATETIME,
last_updated_date DATETIME,
FOREIGN KEY (planting_id) REFERENCES Planting(planting_id)
);
CREATE TABLE Task (
task_id INT PRIMARY KEY,
farm_id INT NOT NULL,
field_id INT NOT NULL,
planting_id INT NOT NULL,
task_type VARCHAR(20) NOT NULL,
title VARCHAR(100),
description TEXT,
priority VARCHAR(10),
status VARCHAR(15),
scheduled_start DATETIME,
scheduled_end DATETIME,
actual_start DATETIME,
actual_end DATETIME,
assigned_worker_id INT,
estimated_cost DECIMAL(8,2),
actual_cost DECIMAL(8,2),
location_description TEXT,
latitude DECIMAL(8,6),
longitude DECIMAL(9,6),
created_date DATETIME,
modified_date DATETIME,
FOREIGN KEY (farm_id) REFERENCES Farm(farm_id),
FOREIGN KEY (field_id) REFERENCES Field(field_id),
FOREIGN KEY (planting_id) REFERENCES Planting(planting_id)
);
CREATE TABLE Gateway (
gateway_id INT PRIMARY KEY,
farm_id INT NOT NULL,
gateway_code VARCHAR(10) NOT NULL,
model VARCHAR(30),
manufacturer VARCHAR(30),
serial_number VARCHAR(30),
connectivity_type VARCHAR(20),
sim_number VARCHAR(15),
ip_address VARCHAR(15),
firmware_version VARCHAR(10),
installed_at DATETIME,
location_description TEXT,
latitude DECIMAL(8,6),
longitude DECIMAL(9,6),
status VARCHAR(10),
last_seen_status DATETIME,
created_date DATETIME,
modified_date DATETIME,
FOREIGN KEY (farm_id) REFERENCES Farm(farm_id)
);
CREATE TABLE Device (
device_id INT PRIMARY KEY,
gateway_id INT NOT NULL,
farm_id INT NOT NULL,
device_code VARCHAR(10) NOT NULL,
model VARCHAR(30),
manufacturer VARCHAR(30),
serial_number VARCHAR(30),
power_type VARCHAR(15),
firmware_version VARCHAR(10),
installed_at DATETIME,
FOREIGN KEY (gateway_id) REFERENCES Gateway(gateway_id),
FOREIGN KEY (farm_id) REFERENCES Farm(farm_id)
);
CREATE TABLE Sensor (
sensor_id INT PRIMARY KEY,
device_id INT NOT NULL,
field_id INT NOT NULL,
sensor_code VARCHAR(10) NOT NULL,
sensor_type VARCHAR(20) NOT NULL,
unit VARCHAR(10),
min_measurement DECIMAL(8,2),
max_measurement DECIMAL(8,2),
accuracy_specification VARCHAR(30),
sampling_interval_second INT,
installed_at DATETIME,
depth_cm DECIMAL(5,1),
position_description TEXT,
latitude DECIMAL(8,6),
longitude DECIMAL(9,6),
status VARCHAR(10),
created_at DATETIME,
last_updated_date DATETIME,
FOREIGN KEY (device_id) REFERENCES Device(device_id),
FOREIGN KEY (field_id) REFERENCES Field(field_id)
);
CREATE TABLE Calibration (
calibration_id INT PRIMARY KEY,
sensor_id INT NOT NULL,
calibration_date DATE NOT NULL,
method VARCHAR(50),
reference_standard VARCHAR(50),
offset_value DECIMAL(6,4),
slope_value DECIMAL(6,4),
performed_by VARCHAR(50),
certificate_number VARCHAR(20),
valid_from_date DATE,
valid_to_date DATE,
additional_note TEXT,
created_date DATETIME,
last_updated_date DATETIME,
FOREIGN KEY (sensor_id) REFERENCES Sensor(sensor_id)
);
CREATE TABLE Reading (
reading_id INT PRIMARY KEY,
sensor_id INT NOT NULL,
reading_time DATETIME NOT NULL,
value DECIMAL(8,2),
unit VARCHAR(10),
quality_flag VARCHAR(10),
raw_payload TEXT,
battery_voltage DECIMAL(4,2),
signal_strength INT,
ingested_at DATETIME,
created_at DATETIME,
FOREIGN KEY (sensor_id) REFERENCES Sensor(sensor_id)
);
CREATE TABLE Alert (
alert_id INT PRIMARY KEY,
farm_id INT NOT NULL,
field_id INT NOT NULL,
sensor_id INT NOT NULL,
alert_type VARCHAR(15) NOT NULL,
severity VARCHAR(10),
title VARCHAR(100),
description TEXT,
triggered_at DATETIME,
acknowledged_at DATETIME,
acknowledged_by VARCHAR(50),
resolved_at DATETIME,
resolution_notes TEXT,
status VARCHAR(15),
FOREIGN KEY (farm_id) REFERENCES Farm(farm_id),
FOREIGN KEY (field_id) REFERENCES Field(field_id),
FOREIGN KEY (sensor_id) REFERENCES Sensor(sensor_id)
);
CREATE TABLE Supplier (
supplier_id INT PRIMARY KEY,
supplier_code VARCHAR(10) NOT NULL,
name VARCHAR(100) NOT NULL,
contact_person VARCHAR(50),
phone VARCHAR(15),
email VARCHAR(50),
address_line1 VARCHAR(50),
address_line2 VARCHAR(50),
city VARCHAR(30),
district VARCHAR(30),
country VARCHAR(30),
tax_id VARCHAR(20),
payment_term VARCHAR(50),
supplier_rating DECIMAL(8,6),
status VARCHAR(10),
created_at DATETIME,
updated_at DATETIME
);
CREATE TABLE Fertilizer (
fertilizer_id INT PRIMARY KEY,
supplier_id INT NOT NULL,
fertilizer_code VARCHAR(10) NOT NULL,
fertilizer_name VARCHAR(100) NOT NULL,
fertilizer_type VARCHAR(20),
formulation VARCHAR(20),
nutrient_n_percent DECIMAL(4,1),
nutrient_p_percent DECIMAL(4,1),
nutrient_k_percent DECIMAL(4,1),
micronutrient TEXT,
unit_of_issue VARCHAR(10),
package_size DECIMAL(6,2),
manufacturer VARCHAR(100),
storage_requirements TEXT,
safety_notes TEXT,
is_active BOOLEAN,
created_at DATETIME,
updated_at DATETIME,
FOREIGN KEY (supplier_id) REFERENCES Supplier(supplier_id)
);
CREATE TABLE PurchaseOrder (
po_id INT PRIMARY KEY,
supplier_id INT NOT NULL,
farm_id INT NOT NULL,
po_number VARCHAR(15) NOT NULL,
po_date DATE,
expected_delivery_date DATE,
currency VARCHAR(3),
subtotal_amount DECIMAL(10,2),
tax_amount DECIMAL(8,2),
total_amount DECIMAL(10,2),
status VARCHAR(15),
note TEXT,
created_at DATETIME,
updated_at DATETIME,
FOREIGN KEY (supplier_id) REFERENCES Supplier(supplier_id),
FOREIGN KEY (farm_id) REFERENCES Farm(farm_id)
);
CREATE TABLE Pesticide (
pesticide_id INT PRIMARY KEY,
supplier_id INT NOT NULL,
pesticide_code VARCHAR(10) NOT NULL,
pesticide_name VARCHAR(100) NOT NULL,
pesticide_type VARCHAR(20),
active_ingredient VARCHAR(100),
concentration VARCHAR(20),
target_pest TEXT,
pre_harvest_interval_day INT,
reentry_interval_hour INT,
toxicity_class VARCHAR(15),
unit_of_issue VARCHAR(10),
package_size DECIMAL(6,2),
manufacturer VARCHAR(100),
safety_note TEXT,
is_active BOOLEAN,
created_at DATETIME,
updated_at DATETIME,
FOREIGN KEY (supplier_id) REFERENCES Supplier(supplier_id)
);
CREATE TABLE Inventory (
inventory_id INT PRIMARY KEY,
farm_id INT NOT NULL,
supplier_id INT NOT NULL,
po_id INT NOT NULL,
item_category VARCHAR(10) NOT NULL,
fertilizer_id INT,
pesticide_id INT,
batch_no VARCHAR(15),
manufacture_date DATE,
expiry_date DATE,
storage_location VARCHAR(30),
unit VARCHAR(10),
quantity_on_hand DECIMAL(10,2),
reorder_level DECIMAL(8,2),
last_stocktake_date DATE,
status VARCHAR(10),
created_at DATETIME,
updated_at DATETIME,
FOREIGN KEY (farm_id) REFERENCES Farm(farm_id),
FOREIGN KEY (supplier_id) REFERENCES Supplier(supplier_id),
FOREIGN KEY (po_id) REFERENCES PurchaseOrder(po_id),
FOREIGN KEY (fertilizer_id) REFERENCES Fertilizer(fertilizer_id),
FOREIGN KEY (pesticide_id) REFERENCES Pesticide(pesticide_id)
);
CREATE TABLE UsageLog (
usage_log_id INT PRIMARY KEY,
farm_id INT NOT NULL,
field_id INT NOT NULL,
planting_id INT,
task_id INT,
inventory_id INT NOT NULL,
usage_date DATETIME NOT NULL,
applied_by VARCHAR(50),
application_method VARCHAR(30),
quantity_used DECIMAL(8,2),
unit VARCHAR(10),
area_covered_ha DECIMAL(6,2),
weather_conditions TEXT,
note TEXT,
created_at DATETIME,
updated_at DATETIME,
FOREIGN KEY (farm_id) REFERENCES Farm(farm_id),
FOREIGN KEY (field_id) REFERENCES Field(field_id),
FOREIGN KEY (planting_id) REFERENCES Planting(planting_id),
FOREIGN KEY (task_id) REFERENCES Task(task_id),
FOREIGN KEY (inventory_id) REFERENCES Inventory(inventory_id)
);
CREATE TABLE Buyer (
buyer_id INT PRIMARY KEY,
buyer_code VARCHAR(10) NOT NULL,
name VARCHAR(100) NOT NULL,
contact_person VARCHAR(50),
phone VARCHAR(15),
email VARCHAR(50),
billing_address_line1 VARCHAR(50),
billing_address_line2 VARCHAR(50),
city VARCHAR(30),
country VARCHAR(30),
delivery_address_line1 VARCHAR(50),
delivery_address_line2 VARCHAR(50),
payment_term VARCHAR(50),
tax_id VARCHAR(20),
status VARCHAR(10),
created_at DATETIME,
updated_at DATETIME
);
CREATE TABLE QualityGrade (
quality_grade_id INT PRIMARY KEY,
grade_code VARCHAR(5) NOT NULL,
description TEXT,
metric_rules TEXT,
min_score DECIMAL(4,1),
max_score DECIMAL(4,1),
is_active BOOLEAN,
created_at DATETIME,
updated_at DATETIME
);
CREATE TABLE Contract (
contract_id INT PRIMARY KEY,
buyer_id INT NOT NULL,
farm_id INT NOT NULL,
crop_id INT,
contract_number VARCHAR(15) NOT NULL,
contract_date DATE,
start_date DATE,
end_date DATE,
agreed_price_per_unit DECIMAL(8,2),
unit VARCHAR(10),
agreed_quantity DECIMAL(10,2),
quality_requirement TEXT,
delivery_term TEXT,
penalty_term TEXT,
status VARCHAR(15),
created_at DATETIME,
updated_at DATETIME,
FOREIGN KEY (buyer_id) REFERENCES Buyer(buyer_id),
FOREIGN KEY (farm_id) REFERENCES Farm(farm_id),
FOREIGN KEY (crop_id) REFERENCES Crop(crop_id)
);
CREATE TABLE Shipment (
shipment_id INT PRIMARY KEY,
contract_id INT NOT NULL,
harvest_id INT,
shipment_number VARCHAR(15) NOT NULL,
shipment_date DATE,
pickup_location TEXT,
dropoff_location TEXT,
transport_provider VARCHAR(100),
vehicle_no VARCHAR(15),
driver_name VARCHAR(50),
gross_weight_kg DECIMAL(8,2),
net_weight_kg DECIMAL(8,2),
packaging_type VARCHAR(20),
packaging_count INT,
temperature_log_ref VARCHAR(30),
status VARCHAR(15),
delivered_at DATETIME,
created_at DATETIME,
updated_at DATETIME,
FOREIGN KEY (contract_id) REFERENCES Contract(contract_id),
FOREIGN KEY (harvest_id) REFERENCES Harvest(harvest_id)
);
CREATE TABLE Invoice (
invoice_id INT PRIMARY KEY,
shipment_id INT NOT NULL,
invoice_number VARCHAR(15) NOT NULL,
invoice_date DATE,
currency VARCHAR(3),
subtotal_amount DECIMAL(10,2),
tax_amount DECIMAL(8,2),
discount_amount DECIMAL(8,2),
total_amount DECIMAL(10,2),
due_date DATE,
status VARCHAR(10),
created_at DATETIME,
updated_at DATETIME,
FOREIGN KEY (shipment_id) REFERENCES Shipment(shipment_id)
);
CREATE TABLE Payment (
payment_id INT PRIMARY KEY,
invoice_id INT NOT NULL,
payment_date DATETIME NOT NULL,
amount_paid DECIMAL(8,2),
currency VARCHAR(3),
payment_method VARCHAR(15),
transaction_ref VARCHAR(20),
received_by VARCHAR(50),
note TEXT,
created_at DATETIME,
updated_at DATETIME,
FOREIGN KEY (invoice_id) REFERENCES Invoice(invoice_id)
);
CREATE TABLE FarmPhone (
farm_id INT NOT NULL,
phone_number VARCHAR(20) NOT NULL,
PRIMARY KEY (farm_id, phone_number),
FOREIGN KEY (farm_id) REFERENCES Farm(farm_id)
);
CREATE TABLE FarmEmail (
farm_id INT NOT NULL,
email_address VARCHAR(30) NOT NULL,
PRIMARY KEY (farm_id, email_address),
FOREIGN KEY (farm_id) REFERENCES Farm(farm_id)
);
